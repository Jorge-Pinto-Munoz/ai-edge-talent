import { createRequire } from "module";
const require = createRequire(import.meta.url);
const { chromium } = require("/opt/node-tools/node_modules/playwright");
const B = "http://localhost:3100";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const errors = []; p.on("pageerror", (e) => errors.push(e.message)); p.on("dialog", (d) => d.accept());
const shot = (n) => p.screenshot({ path: `live/${n}.png` });

await p.goto(B + "/wave-3/postular");
await p.getByRole("link", { name: "Comenzar mi postulación" }).click();
await p.waitForURL(/postular\/registro/);
await p.fill("#full_name", "Paula Prueba Díaz");
await p.fill("#corporate_email", "paula.prueba@kibernum.test");
await p.fill("#client_name", "Cliente Demo Alfa");
await p.fill("#role_title", "QA Lead");
await shot("01-registro");
await p.getByRole("button", { name: /Recibir mi enlace/ }).click();
await p.waitForURL(/postular\/[a-f0-9]{36}$/, { timeout: 15000 });
const token = p.url().split("/").pop();
console.log("token ok", token.length);
await p.getByText("antes de postular queremos que sepas").waitFor();
await shot("02-antes");
const cta = p.getByRole("button", { name: "Entiendo y quiero continuar con mi postulación" });
console.log("cta disabled sin checks:", await cta.isDisabled());
const boxes = p.locator('input[type="checkbox"]');
for (let i = 0; i < await boxes.count(); i++) await boxes.nth(i).check();
await cta.click();
await p.getByRole("heading", { name: "Tu Assessment" }).waitFor({ timeout: 15000 });
const tas = p.locator("textarea");
const n = await tas.count();
for (let i = 0; i < n; i++) await tas.nth(i).fill(`Respuesta concreta ${i + 1}: construí un agente que revisa casos de prueba y abre tickets con revisión humana.`);
await p.getByLabel("A diario").check();
await shot("03-form");
await p.getByRole("button", { name: "Guardar borrador" }).click();
await p.getByText(/Borrador guardado/).waitFor({ timeout: 10000 });
await p.reload();
console.log("borrador persiste:", (await p.locator("textarea").first().inputValue()).startsWith("Respuesta concreta 1"));
await p.getByRole("button", { name: "Enviar mi postulación" }).click();
await p.getByText("Recibimos tu postulación").waitFor({ timeout: 15000 });
await shot("04-enviada");
console.log("TOKEN=" + token);
console.log("errors", errors);
await b.close();
